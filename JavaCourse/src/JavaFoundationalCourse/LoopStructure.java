package JavaFoundationalCourse;

public class LoopStructure {
    public static void main(String[] args){
        int[] arr={1,2,3,4,5};
        for(int a:arr){
            System.out.print(a);
            System.out.print("-");
        }
        System.out.println();
        String[] Stringarr={"a","b","c","d","e"};
        for(String s:Stringarr){
            System.out.print(s);
            System.out.print("-");
        }
    }
}
